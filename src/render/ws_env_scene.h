/* Worldseed Engine — build a renderable scene from a world region.
 *
 * Bridges the P3 world modules (terrain, water, habitat, vegetation,
 * environment) to the renderer's scene contract. Terrain becomes one textured
 * mesh whose per-cell texture encodes the surface class, water becomes a second
 * mesh at the simulated water surface, and trees become instanced cones. The
 * sun direction, sky colours and fog come from the shared environment state, so
 * the picture is driven by the simulation rather than a random post-process.
 *
 * Positions are region-local (floating origin) to keep precision high. All
 * geometry is generated by our own C17 generators (ADR-008).
 */
#ifndef WS_RENDER_ENV_SCENE_H
#define WS_RENDER_ENV_SCENE_H

#include <stddef.h>
#include <stdint.h>

#include "../core/ws_result.h"
#include "../world/ws_environment.h"
#include "../world/ws_habitat.h"
#include "../world/ws_hydro.h"
#include "../world/ws_terrain.h"
#include "../world/ws_vegetation.h"
#include "ws_mesh.h"
#include "ws_scene.h"
#include "ws_texture.h"

#define WS_ENV_MAX_TREES 900u
#define WS_ENV_MAX_OBJECTS (2u + WS_ENV_MAX_TREES)

typedef struct ws_env_scene_options {
    uint64_t seed;
    int64_t region_x;
    int64_t region_y;
    uint32_t cells;        /* region cells per edge */
    double cell_size;      /* metres per cell */
    int scene_kind;        /* 0 = day, 1 = dusk, 2 = weather */
    double time_of_day_s;  /* seconds since local midnight */
} ws_env_scene_options;

ws_env_scene_options ws_env_scene_options_default(uint64_t seed);

typedef struct ws_env_scene {
    /* world layers */
    ws_terrain terrain;
    ws_hydro hydro;
    ws_habitat_map habitat;
    ws_vegetation veg;
    ws_environment env;
    double extent; /* region size in metres */

    /* generated geometry */
    ws_vertex *terrain_verts;
    uint32_t *terrain_idx;
    ws_mesh terrain_mesh;
    ws_texture terrain_tex;

    ws_vertex *water_verts;
    uint32_t *water_idx;
    ws_mesh water_mesh;

    ws_vertex *cone_verts;
    uint32_t *cone_idx;
    ws_mesh cone_mesh;

    ws_scene_object *objects;
    uint32_t object_capacity;
    ws_scene scene;

    uint32_t tree_count;
} ws_env_scene;

/* Generate the region and build the renderable scene. Allocates; the caller
 * must call ws_env_scene_free. */
ws_result ws_env_scene_create(ws_env_scene *env, const ws_env_scene_options *opts);

void ws_env_scene_free(ws_env_scene *env);

/* Stable identifier for a scene kind (for manifests and the app scene list). */
const char *ws_env_scene_kind_id(int scene_kind);

#endif /* WS_RENDER_ENV_SCENE_H */
