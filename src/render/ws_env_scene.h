/* Worldseed Engine — build a renderable scene from a world region.
 *
 * Bridges the P3 world modules (terrain, water, habitat, vegetation,
 * environment) to the renderer's scene contract. Terrain becomes one textured
 * mesh whose per-cell texture encodes the surface class, water becomes a second
 * mesh at the simulated water surface, and trees become instanced cones. The
 * sun direction, sky colours and fog come from the shared environment state, so
 * the picture is driven by the simulation rather than a random post-process.
 *
 * Positions are region-local (floating origin) to keep precision high. All
 * geometry is generated by our own C17 generators (ADR-008).
 */
#ifndef WS_RENDER_ENV_SCENE_H
#define WS_RENDER_ENV_SCENE_H

#include <stddef.h>
#include <stdint.h>

#include "../core/ws_result.h"
#include "../life/ws_agent.h"
#include "../life/ws_creature.h"
#include "../life/ws_quadruped.h"
#include "../world/ws_environment.h"
#include "../world/ws_habitat.h"
#include "../world/ws_hydro.h"
#include "../world/ws_terrain.h"
#include "../world/ws_vegetation.h"
#include "ws_mesh.h"
#include "ws_scene.h"
#include "ws_texture.h"

#define WS_ENV_MAX_TREES 900u
#define WS_ENV_MAX_OBJECTS (3u + WS_ENV_MAX_TREES + 16u)

/* Scene kinds. 0..2 are static environment states; 3 (terrain_physics) drops a
 * rigid body onto the terrain with the P4 solver and renders it where it comes
 * to rest, so the physics result is visible and reproducible. 4 (creature_walk)
 * builds the P5 reference quadruped, drives it with the gait controller for a
 * fixed simulated interval and renders the articulated body mid-stride, so the
 * biomechanics result is visible and reproducible. */
#define WS_ENV_SCENE_DAY 0
#define WS_ENV_SCENE_DUSK 1
#define WS_ENV_SCENE_WEATHER 2
#define WS_ENV_SCENE_PHYSICS 3
#define WS_ENV_SCENE_CREATURE 4
/* 5 (organism_forage) runs the P6 behaviour agent: the animal senses food and
 * water placed from the world layers, chooses a behaviour from its internal
 * drives and walks to the resource it needs, and the scene renders the animal
 * where the decision took it, next to the resource it acted on. */
#define WS_ENV_SCENE_ORGANISM 5

typedef struct ws_env_scene_options {
    uint64_t seed;
    int64_t region_x;
    int64_t region_y;
    uint32_t cells;        /* region cells per edge */
    double cell_size;      /* metres per cell */
    int scene_kind;        /* ws_env_scene_kind constant */
    double time_of_day_s;  /* seconds since local midnight */
} ws_env_scene_options;

ws_env_scene_options ws_env_scene_options_default(uint64_t seed);

typedef struct ws_env_scene {
    /* world layers */
    ws_terrain terrain;
    ws_hydro hydro;
    ws_habitat_map habitat;
    ws_vegetation veg;
    ws_environment env;
    double extent; /* region size in metres */

    /* generated geometry */
    ws_vertex *terrain_verts;
    uint32_t *terrain_idx;
    ws_mesh terrain_mesh;
    ws_texture terrain_tex;

    ws_vertex *water_verts;
    uint32_t *water_idx;
    ws_mesh water_mesh;

    ws_vertex *cone_verts;
    uint32_t *cone_idx;
    ws_mesh cone_mesh;

    /* Physics prop (scene kind 3): a sphere dropped onto the terrain and left
     * where the P4 solver brings it to rest. */
    ws_vertex *rock_verts;
    uint32_t *rock_idx;
    ws_mesh rock_mesh;
    ws_mat4 rock_transform;
    double rock_rest_y; /* final centre height in metres, for evidence */

    /* Reference creature (scene kind 4): the simulated articulated body, kept so
     * its final link poses can be rendered. `cube_mesh` is one unit-cube mesh
     * reused for every link. */
    ws_cbody creature_bodies[8];
    uint32_t creature_body_count;
    ws_quad_parts creature_parts;
    ws_vertex *cube_verts;
    uint32_t *cube_idx;
    ws_mesh cube_mesh;
    double creature_z;         /* region-local z of the walking line, m */
    double creature_forward_m; /* distance walked in metres, for evidence */
    int creature_contact;      /* feet in contact at the rendered instant */

    /* Behaviour organism (scene kind 5): the P6 agent's final decision and the
     * resource it acted on, kept so the visible picture reflects the simulated
     * behaviour rather than a scripted pose. */
    ws_agent organism;
    int organism_behavior;     /* ws_behavior at the rendered instant */
    double organism_dist_m;    /* distance travelled, m */
    uint32_t organism_food_found;
    uint32_t organism_water_found;
    double resource_x;         /* region-local position of the acted-on resource */
    double resource_z;
    int resource_kind;         /* ws_sense_kind, or -1 when none */
    double resource_value;     /* remaining value 0..1 */

    ws_scene_object *objects;
    uint32_t object_capacity;
    ws_scene scene;

    uint32_t tree_count;
} ws_env_scene;

/* Generate the region and build the renderable scene. Allocates; the caller
 * must call ws_env_scene_free. */
ws_result ws_env_scene_create(ws_env_scene *env, const ws_env_scene_options *opts);

void ws_env_scene_free(ws_env_scene *env);

/* Stable identifier for a scene kind (for manifests and the app scene list). */
const char *ws_env_scene_kind_id(int scene_kind);

#endif /* WS_RENDER_ENV_SCENE_H */
